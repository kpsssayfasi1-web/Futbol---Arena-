// Precomputes catalog measurements so the page never measures shapes at runtime.
// Run after changing any shape:  node tools/build-meta.mjs
import { writeFileSync } from 'node:fs';
import { ITEMS } from '../js/catalog/index.js';
import { measure, shapeHash } from '../js/object-info.js';

const r = (v) => Math.round(v * 1e4) / 1e4;
const out = {};
for (const item of ITEMS) {
  const m = measure(item);
  const { bits, G, x0, z0, cx, cz } = m.fpRaw;
  const packed = new Uint8Array(Math.ceil((G * G) / 8));
  for (let b = 0; b < G * G; b++) if (bits[b]) packed[b >> 3] |= 1 << (b & 7);
  out[item.id] = {
    hash: shapeHash(item),
    bbox: { min: m.bbox.min.map(r), max: m.bbox.max.map(r) },
    boardY: r(m.boardY), volume: r(m.volume), areas: m.areas.map(r), widths: m.widths.map(r),
    fp: Buffer.from(packed).toString('base64'), fpGrid: { G, x0: r(x0), z0: r(z0), cx: r(cx), cz: r(cz) },
  };
}
const body = Object.entries(out).map(([id, m]) => `  ${JSON.stringify(id)}: ${JSON.stringify(m)},`).join('\n');
writeFileSync(new URL('../js/catalog/meta.js', import.meta.url), `// Generated by tools/build-meta.mjs. Do not edit by hand.\nexport const META = {\n${body}\n};\n`);
console.log(`meta for ${ITEMS.length} items`);
